"""BackStudio CLI entry point."""

import os
import secrets
import subprocess
import sys
import webbrowser
from pathlib import Path

import typer

from app.erd.loader import ERDValidationError, load_erd
from app.erd.translate import translate
from app.erd.visualize import render_html
from app.services.code_generator import CodeGenerator

app = typer.Typer(name="backstudio", help="Generate FastAPI backends from a YAML ERD.")

_MAX_SUBPROCESS_OUTPUT = 4000


def _decode_and_truncate(output: object) -> str:
    """Decode subprocess stdout/stderr (bytes or str) and cap it to a sane length."""
    if not output:
        return ""
    text = output.decode("utf-8", errors="replace") if isinstance(output, bytes) else str(output)
    text = text.strip()
    if not text:
        return ""
    if len(text) > _MAX_SUBPROCESS_OUTPUT:
        text = text[:_MAX_SUBPROCESS_OUTPUT] + "\n... (truncated)"
    return text + "\n"


def _ensure_dev_env_secret(project_dir: Path, secret_env_var: str) -> str | None:
    """Write a freshly-generated random secret to <project_dir>/.env for local dev.

    Does nothing (returns None) if the env var is already set in the current process,
    or if a .env file already exists (never overwrites one, e.g. on a --force
    regeneration where the user may have already customized it). Returns the path
    written to on success, for the caller to report to the user.
    """
    if os.getenv(secret_env_var):
        return None

    env_path = project_dir / ".env"
    if env_path.exists():
        return None

    secret_value = secrets.token_hex(32)
    env_path.write_text(
        f"# Auto-generated by `backstudio generate` for local development.\n"
        f"# Replace with a securely-managed secret before deploying anywhere real.\n"
        f"{secret_env_var}={secret_value}\n",
        encoding="utf-8",
    )
    # Make it available in this process too, so the Alembic subprocess below (which
    # inherits the current environment) can actually use it without a second run.
    os.environ[secret_env_var] = secret_value
    return str(env_path)


